import apiClient from "./client";
import { mockRecommendations } from "../data/mockData";

const USE_MOCK = false; // Live backend endpoint connected: GET /api/recommendations

function formatActionLabel(actionType, targetMarket) {
  switch (actionType) {
    case "SELL_LOCAL":
      return "Sell locally";
    case "MOVE_TO_MARKET":
      return targetMarket ? `Move to ${targetMarket}` : "Ship to high-demand location";
    case "DISCOUNT":
      return "Discount now";
    case "PROCESS":
      return "Redirect to processing";
    case "REDIRECT":
      return "Redirect to alternative channel";
    case "URGENT_SELL":
      return "Urgent sell immediately";
    case "HOLD":
      return "Hold & monitor";
    default:
      return actionType || "Sell locally";
  }
}

export async function getRecommendations() {
  if (USE_MOCK) return Promise.resolve(mockRecommendations);
  try {
    const response = await apiClient.get("/recommendations");
    const rawList = response.data?.data || response.data || [];
    if (!Array.isArray(rawList)) return [];

    return rawList.map((r) => {
      const batch = r.batchId || {};
      return {
        id: r._id || r.id,
        batchId: batch.batchCode || batch._id || (typeof r.batchId === "string" ? r.batchId : "BATCH"),
        produce: batch.productName || batch.produceType || "Produce",
        quantityKg: batch.quantity || r.expectedWasteKg || 0,
        urgency: (r.urgencyLevel || "medium").toLowerCase(),
        action: formatActionLabel(r.actionType, r.targetMarket),
        reason: r.reason || "Recommendation generated by decision engine.",
      };
    });
  } catch (error) {
    console.error("Failed to fetch recommendations from backend:", error);
    return mockRecommendations;
  }
}
